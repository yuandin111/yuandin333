-- 论坛 + 好友功能 初始化脚本（MySQL 8 / utf8mb4）
-- 包含：6 张业务表 + 示例用户 + 同人二创等板块种子帖 + 评论 + 好友关系 + 私信
-- ⚠ 会 DROP 并重建下面 6 张表，仅用于首次初始化或需要重置示例数据时执行；
--    不会动 sys_user 已有的账号之外的任何既有资料表。
-- 执行：mysql -uroot -p123456 --default-character-set=utf8mb4 -D springboot_test < forum_friends_init.sql
-- =============================================================
SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

DROP TABLE IF EXISTS `friend_message`;
DROP TABLE IF EXISTS `friendship`;
DROP TABLE IF EXISTS `friend_request`;
DROP TABLE IF EXISTS `forum_like`;
DROP TABLE IF EXISTS `forum_comment`;
DROP TABLE IF EXISTS `forum_post`;

-- ---------------------------- 论坛帖子 ----------------------------
CREATE TABLE `forum_post` (
  `id` bigint NOT NULL AUTO_INCREMENT COMMENT '帖子ID',
  `title` varchar(120) NOT NULL COMMENT '标题',
  `content` text NOT NULL COMMENT '正文',
  `category` varchar(32) NOT NULL DEFAULT 'fanwork' COMMENT '板块：fanwork同人二创/fanart同人图绘/discuss剧情讨论/lore术式考据/chat闲聊水区',
  `tags` varchar(200) DEFAULT NULL COMMENT '标签，英文逗号分隔',
  `cover_url` varchar(255) DEFAULT NULL COMMENT '封面图URL（可空，前端回退渐变卡片）',
  `author_id` bigint NOT NULL COMMENT '作者用户ID',
  `author_name` varchar(50) NOT NULL COMMENT '作者用户名（冗余，避免列表联表）',
  `like_count` int NOT NULL DEFAULT 0 COMMENT '点赞数',
  `comment_count` int NOT NULL DEFAULT 0 COMMENT '评论数',
  `view_count` int NOT NULL DEFAULT 0 COMMENT '浏览量',
  `is_top` tinyint NOT NULL DEFAULT 0 COMMENT '是否置顶',
  `is_essence` tinyint NOT NULL DEFAULT 0 COMMENT '是否精华',
  `status` tinyint NOT NULL DEFAULT 1 COMMENT '1正常 0已删除',
  `create_time` datetime DEFAULT NULL,
  `update_time` datetime DEFAULT NULL,
  PRIMARY KEY (`id`),
  KEY `idx_category` (`category`),
  KEY `idx_create_time` (`create_time`),
  KEY `idx_author` (`author_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='论坛帖子';

-- ---------------------------- 论坛评论/回复 ----------------------------
CREATE TABLE `forum_comment` (
  `id` bigint NOT NULL AUTO_INCREMENT COMMENT '评论ID',
  `post_id` bigint NOT NULL COMMENT '帖子ID',
  `parent_id` bigint DEFAULT NULL COMMENT '被回复的评论ID，NULL 表示楼层主评',
  `reply_to_name` varchar(50) DEFAULT NULL COMMENT '被回复者用户名',
  `user_id` bigint NOT NULL COMMENT '评论者ID',
  `user_name` varchar(50) NOT NULL COMMENT '评论者用户名',
  `content` varchar(1000) NOT NULL COMMENT '评论内容',
  `like_count` int NOT NULL DEFAULT 0,
  `status` tinyint NOT NULL DEFAULT 1 COMMENT '1正常 0已删除',
  `create_time` datetime DEFAULT NULL,
  PRIMARY KEY (`id`),
  KEY `idx_post` (`post_id`),
  KEY `idx_parent` (`parent_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='论坛评论与回复';

-- ---------------------------- 帖子点赞 ----------------------------
CREATE TABLE `forum_like` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `post_id` bigint NOT NULL,
  `user_id` bigint NOT NULL,
  `create_time` datetime DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_post_user` (`post_id`,`user_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='帖子点赞（一人一帖一次）';

-- ---------------------------- 好友申请 ----------------------------
CREATE TABLE `friend_request` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `from_user_id` bigint NOT NULL COMMENT '发起人',
  `from_user_name` varchar(50) NOT NULL,
  `to_user_id` bigint NOT NULL COMMENT '接收人',
  `to_user_name` varchar(50) NOT NULL,
  `message` varchar(200) DEFAULT NULL COMMENT '验证消息',
  `status` tinyint NOT NULL DEFAULT 0 COMMENT '0待处理 1已同意 2已拒绝',
  `create_time` datetime DEFAULT NULL,
  `handle_time` datetime DEFAULT NULL,
  PRIMARY KEY (`id`),
  KEY `idx_to` (`to_user_id`,`status`),
  KEY `idx_from` (`from_user_id`,`status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='好友申请';

-- ---------------------------- 好友关系（双向各存一条） ----------------------------
CREATE TABLE `friendship` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `user_id` bigint NOT NULL,
  `friend_id` bigint NOT NULL,
  `friend_name` varchar(50) NOT NULL,
  `create_time` datetime DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_user_friend` (`user_id`,`friend_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='好友关系';

-- ---------------------------- 好友私信 ----------------------------
CREATE TABLE `friend_message` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `from_user_id` bigint NOT NULL,
  `to_user_id` bigint NOT NULL,
  `content` varchar(1000) NOT NULL,
  `is_read` tinyint NOT NULL DEFAULT 0 COMMENT '0未读 1已读',
  `create_time` datetime DEFAULT NULL,
  PRIMARY KEY (`id`),
  KEY `idx_pair` (`from_user_id`,`to_user_id`,`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='好友私信';

